const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

async function checkVehicleFolders({ evaluate, call, artifacts, suffix }) {
  const pause = () => new Promise(resolve => setTimeout(resolve, 160));
  await evaluate("els.countrySelect.value='usa';els.typeSelect.value='ground';loadTree()");
  await pause();
  const ids = await evaluate(`(() => {
    const button = document.querySelector('[data-folder-key]');
    const group = state.groupMap.get(button.dataset.folderGroup);
    return {key:button.dataset.folderKey, main:group.items[0].data_unit_id, child:group.items[1].data_unit_id, count:group.items.length};
  })()`);
  const button = `document.querySelector('[data-folder-key="${ids.key}"]')`;
  const popup = "document.querySelector('.folder-popup')";
  const tile = `${popup}.querySelector('[data-unit-id="${ids.child}"]')`;
  const budget = () => evaluate("JSON.stringify([els.budgetCount.textContent,els.budgetRp.textContent,els.budgetSl.textContent])");
  assert(await evaluate(`${popup}.hidden && !els.treeContainer.querySelector('[data-unit-id="${ids.child}"]')`), 'Folded children stay out of the tree');
  assert.equal(await evaluate(`${button}.getBoundingClientRect().width`), 28);
  await evaluate(`(() => {
    const rect=${button}.closest('.folder-tile').getBoundingClientRect(), tree=els.treeContainer;
    tree.scrollTop+=rect.top-tree.getBoundingClientRect().top-50;
    tree.scrollLeft+=rect.left-tree.getBoundingClientRect().left-104;
  })()`);
  await pause();
  const height = await evaluate("els.treeContainer.scrollHeight");
  const before = await budget();
  let shot = await call('Page.captureScreenshot',{format:'png'});
  fs.writeFileSync(path.join(artifacts,suffix+'-folder-closed.png'),Buffer.from(shot.data,'base64'));
  await evaluate(`${button}.focus()`);
  await call('Input.dispatchKeyEvent',{type:'keyDown',key:'Enter',code:'Enter',windowsVirtualKeyCode:13,text:'\r'});
  await call('Input.dispatchKeyEvent',{type:'keyUp',key:'Enter',code:'Enter',windowsVirtualKeyCode:13});
  await pause();
  assert(await evaluate(`!${popup}.hidden`));
  assert(await evaluate("!document.querySelector('.folder-focus-backdrop').hidden && getComputedStyle(document.querySelector('.folder-focus-backdrop')).backdropFilter.includes('blur')"),'Opening focuses the popup with a blurred backdrop');
  assert.equal(await evaluate(`${popup}.querySelectorAll('.unit-tile').length`),ids.count);
  assert.equal(await evaluate("els.treeContainer.scrollHeight"),height,'Popup must not stretch the tree');
  assert(await evaluate(`(() => {
    const a=${button}.closest('.folder-tile').getBoundingClientRect(), p=${popup}.getBoundingClientRect();
    const expected=Math.max(12,Math.min(a.left+(a.width-p.width)/2,innerWidth-p.width-12));
    return Math.abs(expected-p.left)<=1 && p.width<=218;
  })()`),'Compact popup remains centered on its folder');
  assert.equal(await budget(),before);
  assert(await evaluate(`${popup}.querySelectorAll('.tree-links > path').length > 0`),'Actual folder prerequisites have arrows');
  assert(await evaluate(`getComputedStyle(${popup}.querySelector('.tree-links')).display !== 'none'`),'Arrows remain visible on small screens');
  assert(await evaluate(`(() => {
    const r=${popup}.getBoundingClientRect();
    return r.left>=0 && r.top>=0 && r.right<=innerWidth && r.bottom<=innerHeight;
  })()`),'Popup stays inside viewport');
  assert(await evaluate(`[...${popup}.querySelectorAll('.unit-tile')].every(tile => {
    const r=tile.getBoundingClientRect(), p=${popup}.getBoundingClientRect();
    return r.left>=p.left && r.right<=p.right && tile.scrollWidth<=tile.clientWidth+1;
  })`),'Cards and text fit the compact panel');
  await evaluate(`${tile}.click()`);
  await pause();
  assert(await evaluate(`!${popup}.hidden && state.planned.has("${ids.child}")`),'Selection keeps the popup open');
  const selected = await budget();
  await evaluate(`${tile}.dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:100,clientY:250}))`);
  assert(await evaluate("!els.unitContextMenu.hidden"));
  await evaluate("els.unitContextMenu.querySelector('[data-context-action=owned]').click()");
  await pause();
  assert(await evaluate(`state.owned.has("${ids.child}") && !${popup}.hidden`),'Context actions work inside popup');
  await evaluate(`toggleUnitMode("${ids.child}","owned");toggleUnitMode("${ids.child}","target")`);
  await pause();
  await evaluate("setLanguage('en')");
  await pause();
  assert(await evaluate(`!${popup}.hidden`),'Language change keeps popup');
  await evaluate("setLanguage('zh')");
  await pause();
  shot = await call('Page.captureScreenshot',{format:'png'});
  fs.writeFileSync(path.join(artifacts,suffix+'-folder-open.png'),Buffer.from(shot.data,'base64'));
  await call('Input.dispatchKeyEvent',{type:'keyDown',key:'Escape',code:'Escape',windowsVirtualKeyCode:27});
  await pause();
  assert(await evaluate(`${popup}.hidden && document.activeElement === ${button}`),'Escape closes and restores focus');
  assert(await evaluate("document.querySelector('.folder-focus-backdrop').hidden"),'Closing removes background blur');
  const closed = await budget();
  await evaluate(`${button}.click()`);
  await pause();
  assert.equal(await budget(),closed,'Open/close preserves totals');
  await call('Input.dispatchMouseEvent',{type:'mousePressed',x:5,y:5,button:'left',clickCount:1});
  await call('Input.dispatchMouseEvent',{type:'mouseReleased',x:5,y:5,button:'left',clickCount:1});
  assert(await evaluate(`${popup}.hidden`),'Outside click closes');
  assert(await evaluate("document.querySelector('.folder-focus-backdrop').hidden"),'Outside click restores clear page');
  await evaluate(`els.searchInput.value="${ids.child}";els.searchInput.dispatchEvent(new Event('input'))`);
  await pause();
  assert(await evaluate(`${popup}.hidden && ${button}.classList.contains('has-match')`));
  await evaluate(`${button}.click()`);
  await pause();
  await evaluate("els.countrySelect.value='israel';els.typeSelect.value='aviation';loadTree()");
  await pause();
  assert(await evaluate(`${popup}.hidden`),'Tree switch closes stale popup');
  await evaluate("els.searchInput.value='';els.searchInput.dispatchEvent(new Event('input'));els.countrySelect.value='usa';els.typeSelect.value='ground';loadTree()");
  await pause();
  await evaluate(`if(state.planned.has("${ids.child}")) toggleUnitMode("${ids.child}","target");`);
  const count = () => evaluate(`Number(${button}.closest('.folder-tile').querySelector('.folder-selection-count')?.dataset.selectedCount || 0)`);
  await evaluate("state.planned.clear();state.owned.clear();state.waypoints.clear();invalidateExactPlan();calculatePlan()");
  assert.equal(await count(),0);
  await evaluate(`toggleUnitMode("${ids.main}","target");toggleUnitMode("${ids.child}","target")`);
  assert.equal(await count(),2,'Count includes both the main vehicle and folded child');
  await evaluate(`toggleUnitMode("${ids.child}","waypoint")`);
  assert.equal(await count(),2,'Switching a target to a waypoint does not double count');
  await evaluate(`toggleUnitMode("${ids.child}","owned")`);
  assert.equal(await count(),1,'Owned vehicles are excluded from selection count');
  await evaluate(`toggleUnitMode("${ids.main}","target")`);
  assert.equal(await count(),0,'Badge disappears when no targets or waypoints remain');
  await evaluate(`toggleUnitMode("${ids.child}","target");toggleUnitMode("${ids.main}","target");setLanguage('en')`);
  assert.equal(await count(),2);
  assert(await evaluate(`${button}.closest('.folder-tile').querySelector('.folder-selection-count').textContent === '2 selected'`));
  await evaluate("loadTree()");
  await pause();
  assert.equal(await count(),2,'Selection count survives saved-state reload');
  assert(await evaluate(`(() => {
    const badge=${button}.closest('.folder-tile').querySelector('.folder-selection-count');
    const a=badge.getBoundingClientRect(), b=${button}.getBoundingClientRect();
    return badge.scrollWidth<=badge.clientWidth+1 && (a.right<=b.left || a.top>=b.bottom);
  })()`),'English badge fits and does not overlap the toggle');
  await evaluate("setLanguage('zh')");
  await evaluate(`(() => {
    const rect=${button}.closest('.folder-tile').getBoundingClientRect(), tree=els.treeContainer;
    tree.scrollTop+=rect.top-tree.getBoundingClientRect().top-50;
    tree.scrollLeft+=rect.left-tree.getBoundingClientRect().left-104;
  })()`);
  await pause();
  shot=await call('Page.captureScreenshot',{format:'png'});
  fs.writeFileSync(path.join(artifacts,suffix+'-folder-count.png'),Buffer.from(shot.data,'base64'));
  await evaluate(`toggleUnitMode("${ids.main}","target");toggleUnitMode("${ids.child}","target")`);
  assert.equal(await count(),0);
  console.log(JSON.stringify({folders:suffix,compactToggle:true,popup:true,arrows:true,selection:true,context:true,keyboard:true,fit:true}));
}
module.exports = { checkVehicleFolders };
